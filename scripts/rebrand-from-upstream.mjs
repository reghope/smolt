// pi -> smolt rebrand script. Run at repo root: node rebrand.mjs [--apply]
// Without --apply it reports what would change.

import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const APPLY = process.argv.includes("--apply");

const EXCLUDE = [
	/^README\.md$/, // root README keeps deliberate upstream attribution
	/^LICENSE/i,
	/CHANGELOG\.md$/i, // historical upstream text stays factual
	/^package-lock\.json$/, // regenerated by npm install
	/npm-shrinkwrap\.json$/, // regenerated by scripts
	/packages\/tui\/src\/latex\.ts$/, // \pi -> π math mapping must survive
	/\.(png|ico|jpg|jpeg|gif|woff2?|ttf)$/i,
];

const files = execSync("git ls-files", { encoding: "utf-8" })
	.split("\n")
	.filter(Boolean)
	.filter((f) => !EXCLUDE.some((re) => re.test(f)));

const UP = "@@UPSTREAM@@";
const PD = "@@PIDEV@@";

const rules = [
	// 1. Workspace package scope
	{ name: "scope", re: /@earendil-works\/pi-/g, to: "@smolt/" },
	// 2-3. Protect upstream project references (attribution / real URLs)
	{ name: "protect-upstream", re: /earendil-works\/pi/g, to: UP },
	{ name: "protect-pidev", re: /pi\.dev/g, to: PD },
	// 4. camelCase: piConfig -> smoltConfig, getPiUserAgent -> getSmoltUserAgent
	{ name: "camel-lower", re: /(?<![A-Za-z0-9_])pi(?=[A-Z])/g, to: "smolt" },
	{ name: "camel-upper", re: /(?<=[A-Za-z0-9])Pi(?![a-z])/g, to: "Smolt" },
	// 5. snake_case
	{ name: "snake-pre", re: /(?<![A-Za-z0-9])pi(?=_)/g, to: "smolt" },
	{ name: "snake-post", re: /(?<=_)pi(?![A-Za-z0-9])/g, to: "smolt" },
	// 6. bare words (covers "pi", "pi-manifest", ".pi", "'pi'", "Pi", "PI")
	{ name: "word-lower", re: /(?<![A-Za-z0-9_])pi(?![A-Za-z0-9_])/g, to: "smolt" },
	{ name: "word-title", re: /(?<![A-Za-z0-9_])Pi(?![A-Za-z0-9_])/g, to: "Smolt" },
	{ name: "word-upper", re: /(?<![A-Za-z0-9_])PI(?![A-Za-z0-9_])/g, to: "SMOLT" },
	// 7. restore protections
	{ name: "restore-upstream", re: new RegExp(UP, "g"), to: "earendil-works/pi" },
	{ name: "restore-pidev", re: new RegExp(PD, "g"), to: "pi.dev" },
];

const ruleCounts = {};
const touched = [];
const samples = {};

for (const file of files) {
	let text;
	try {
		text = readFileSync(file, "utf-8");
	} catch {
		continue;
	}
	if (text.includes(String.fromCharCode(0))) continue; // binary
	let out = text;
	for (const rule of rules) {
		const before = out;
		out = out.replace(rule.re, rule.to);
		if (out !== before && !rule.name.startsWith("protect") && !rule.name.startsWith("restore")) {
			ruleCounts[rule.name] = (ruleCounts[rule.name] ?? 0) + 1;
		}
	}
	if (out !== text) {
		touched.push(file);
		if (APPLY) writeFileSync(file, out, "utf-8");
		else {
			// capture a couple of example diffs per extension for review
			const ext = file.split(".").pop();
			if (!samples[ext]) {
				const origLines = text.split("\n");
				const newLines = out.split("\n");
				const diffs = [];
				for (let i = 0; i < origLines.length && diffs.length < 3; i++) {
					if (origLines[i] !== newLines[i]) diffs.push(`  - ${origLines[i].trim().slice(0, 90)}\n  + ${newLines[i].trim().slice(0, 90)}`);
				}
				samples[ext] = `${file}:\n${diffs.join("\n")}`;
			}
		}
	}
}

console.log(`${APPLY ? "APPLIED" : "DRY RUN"}: ${touched.length} files changed of ${files.length} scanned`);
console.log("files per rule:", JSON.stringify(ruleCounts));
if (!APPLY) {
	for (const s of Object.values(samples)) console.log(`\n${s}`);
}
